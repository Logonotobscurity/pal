/**
 * Record a sample measured benchmark run.
 *
 * Usage:
 *   npx tsx scripts/benchmark/record-sample-run.ts
 *
 * Writes a timestamped JSON + markdown report under benchmarks/runs/
 * so the measured-results path is exercised even before a full dataset eval.
 */

import { writeFileSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const outDir = join(process.cwd(), "benchmarks", "runs");
mkdirSync(outDir, { recursive: true });

const timestamp = new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);
const model = process.env.OPENAI_MODEL ?? "gpt-4o-mini";

const result = {
  model,
  dataset: "sample",
  timestamp: new Date().toISOString(),
  total_samples: 3,
  successful_samples: 3,
  note: "Scaffolded sample run — replace with real evaluate-pipeline.ts output when the full dataset is available.",
  tier1: { avg_wer: null, avg_code_switch_detection: null, pass_rate: null },
  tier2: { critical_field_recall: null, critical_field_precision: null },
  tier3: { intent_accuracy: null },
  tier4: { action_validity: null, policy_compliance: null },
  tier5: { critical_field_blocking: null, provenance_coverage: null },
  overall_pal_score: null,
  results: [],
};

const jsonPath = join(outDir, `${timestamp}_${model}_sample.json`);
writeFileSync(jsonPath, JSON.stringify(result, null, 2));

const md = `# PAL Benchmark Report (sample)

**Model**: ${model}
**Dataset**: sample (scaffolding)
**Timestamp**: ${result.timestamp}
**Overall PAL Score**: not yet measured

This file was generated by \`scripts/benchmark/record-sample-run.ts\` to exercise the
results path. Replace it with output from \`npm run benchmark:eval\` once the
AfriSwitchCare dataset is loaded and a full run completes.

## Status

- [x] Results directory scaffolding
- [ ] Full dataset loaded
- [ ] Measured 5-tier run completed
`;

const mdPath = join(outDir, `${timestamp}_${model}_sample_report.md`);
writeFileSync(mdPath, md);

console.log(`Wrote sample run:\n  ${jsonPath}\n  ${mdPath}`);
